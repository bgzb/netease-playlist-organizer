export type Source = 'songDetail' | 'desktopWiki' | 'ugcSong' | 'manual' | 'none';
export type Field<T> = { value: T | null; source: Source;
  status: 'known' | 'missing' | 'error'; reason?: string };
export type Artist = { id: string; name: string };
export type SongRecord = { id: string; name: string; position: number;
  artists: Field<Artist[]>; genres: Field<string[]>;
  bpm: Field<number>; language: Field<string> };
export type Filters = { genres: string[]; languages: string[]; artistIds: string[];
  bpmMin: number | null; bpmMax: number | null; allSongs: boolean };
export type FilterResult = { matched: SongRecord[]; unknown: SongRecord[];
  unmatched: SongRecord[]; reasons: Record<string, string[]> };
export type SourceSelection = {kind:'favorites'} | {kind:'playlist';id:string};
export type PlaylistDescriptor = {id:string;name:string;creatorUid:string};
export type SourceCatalog = {uid:string;favoritesId:string;created:PlaylistDescriptor[];collected:PlaylistDescriptor[]};
export type LibrarySnapshot = { uid: string; sourcePlaylistId: string; source?:PlaylistDescriptor;
  declaredCount: number; ids: string[]; songs: SongRecord[]; revision: string };
export type Progress = { processed: number; total: number;
  phase: 'reading' | 'scanning' | 'pausing' | 'paused' | 'complete' | 'error' };
export type ReadPath = '/api/w/nuser/account/get' | '/api/user/playlist'
  | '/api/v6/playlist/detail' | '/api/v3/song/detail' | '/api/rep/ugc/song/get';
export type CapabilityReport = { supported: boolean; adapterVersion: string; reasons: string[];
  read: ((path: ReadPath, data: Record<string, unknown>, signal?: AbortSignal) => Promise<unknown>) | null;
  write?: import('../client/requests').WriteApi | null;
  desktopWiki: ((id: string, signal?: AbortSignal) => Promise<{ metas: { title: string; content: string }[] } | null>) | null };
export type CacheEntry = { song: SongRecord;
  updatedAt: { genres: number; bpm: number; language: number } };
export type ScanCheckpoint = { snapshot: LibrarySnapshot; completedIds: string[];
  cache: Record<string, CacheEntry>; phase: Progress['phase']; updatedAt: number };
export type StoredPlaylistScan = {schemaVersion:2;uid:string;source:PlaylistDescriptor;checkpoint:ScanCheckpoint;lastCompletedAt:number|null};
export type ScanSummary = {source:PlaylistDescriptor;phase:Progress['phase'];processed:number;total:number;updatedAt:number;lastCompletedAt:number|null};
export type PersistedState = { schemaVersion: 1; uid: string;
  scan: ScanCheckpoint | null; writeJournal: WriteJournal | null };
export type WritePlan = { taskId: string; uid: string; sourcePlaylistId: string;
  sourceRevision: string; selectionVersion: string; songIds: string[];
  target: { kind: 'new'; name: string; privacy: 10 } | { kind: 'existing'; id: string } };
export type WriteConfirmation = { uid: string; sourcePlaylistId:string; sourceRevision: string;
  selectionVersion: string; targetKey: string; confirmedAt: number };
export type WriteProgress = { phase: 'creating' | 'adding' | 'verifying' | 'paused' | 'complete' | 'error';
  total: number; added: number; alreadyPresent: number; failed: number; targetId: string | null };
export type WriteReport = { taskId: string; targetId: string | null;
  status: 'complete' | 'paused' | 'uncertain' | 'error'; addedIds: string[];
  alreadyPresentIds: string[]; unconfirmedIds: string[]; errors: string[] };
export type WriteJournal = { plan: WritePlan; targetId: string | null; beforePlaylistIds: string[];
  creationState: 'notStarted' | 'pending' | 'confirmed' | 'uncertain';
  batches: { ids: string[]; state: 'pending' | 'confirmed' | 'uncertain' }[];
  confirmedIds: string[]; updatedAt: number;
  review?: {filters:Filters; addedIds:string[]; removedIds:string[]};
  readbackIds?: string[]; operations?: {kind: string; state: 'pending' | 'confirmed' | 'error'}[] };
